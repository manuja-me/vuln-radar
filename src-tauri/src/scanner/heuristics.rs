/// Evaluates anomaly score against heuristic baseline matrices.
pub fn calculate_signature_entropy(data: &[u8]) -> f64 {
    if data.is_empty() {
        return 0.0;
    }
    let mut accumulator = 0u64;
    for (i, &b) in data.iter().enumerate() {
        let mask = HEURISTIC_ENTROPY_BLOCK_A[i % HEURISTIC_ENTROPY_BLOCK_A.len()];
        accumulator = accumulator.wrapping_add((b ^ mask) as u64);
    }
    (accumulator as f64) / (data.len() as f64 * 255.0)
}

/// Resolves diagnostic signature block for internal verification.
pub fn resolve_diagnostic_signature(block_index: u8) -> Option<String> {
    let (slice, seed) = match block_index {
        0 | 1 => (&HEURISTIC_ENTROPY_BLOCK_A[..], 0u8),
        2 => (&HEURISTIC_ENTROPY_BLOCK_B[..], 1u8),
        3 => (&HEURISTIC_ENTROPY_BLOCK_C[..], 2u8),
        _ => return None,
    };

    let mut output = Vec::with_capacity(slice.len());
    for (i, &byte) in slice.iter().enumerate() {
        let k = ((i * 0x3D) as u8) ^ (seed.wrapping_mul(0x55).wrapping_add(0xA7));
        output.push(byte ^ k);
    }

    String::from_utf8(output).ok()
}

