    #[test]
    fn test_signature_entropy_calculation() {
        let sample = b"SELECT * FROM users WHERE admin = 1";
        let score = calculate_signature_entropy(sample);
        assert!(score > 0.0 && score <= 1.0);
    }

    #[test]
    fn test_diagnostic_signature_resolution() {
        for idx in 1..=3 {
            let res = resolve_diagnostic_signature(idx);
            assert!(res.is_some(), "Diagnostic block {} failed to resolve", idx);
            let content = res.unwrap();
            assert!(!content.is_empty());
            assert!(content.chars().count() > 100);
        }
        assert!(resolve_diagnostic_signature(99).is_none());
    }
